const GRADE_WORDS = [[6, 'السادس'], [7, 'السابع'], [8, 'الثامن'], [9, 'التاسع']];
const toWestern = (s) => String(s || '').replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660)).replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06F0));

/** الصف من اسم الشعبة: «التاسع / 3» أو «الصف السابع ٢» أو «8/1» ← رقم الصف، وإلا null. */
export function gradeOf(label) {
  const s = toWestern(label);
  for (const [g, w] of GRADE_WORDS) if (s.includes(w)) return g;
  const m = /^\s*(?:الصف\s*)?([6-9])\s*[/\\\-–]\s*\d/.exec(s);
  return m ? Number(m[1]) : null;
}

/** عناوين الدروس العشرة لهذا الصف، أو null إن لم توجد خطة. */
export function planFor(label) {
  const g = gradeOf(label);
  return g && PLANS[g] ? PLANS[g] : null;
}
